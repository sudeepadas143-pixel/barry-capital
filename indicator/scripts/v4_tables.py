"""Render reports/v4_root_cause.json (scripts/v4_root_cause.py) as reports/V4_TABLES.md."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = json.loads((ROOT / "reports" / "v4_root_cause.json").read_text())
TFS = ["1H", "4H", "1D", "1W"]
GROUPS = ["crypto", "equities", "commodities", "rates_fx", "all"]


def f(x, nd=2, sign=True):
    if x is None:
        return "–"
    return f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"


def ci(v):
    return f"{f(v[0])} [{f(v[1])}, {f(v[2])}]"


L = ["# V4 tables (generated by scripts/v4_tables.py from reports/v4_root_cause.json)", "",
     "Plan: [`V4_ANALYSIS_PLAN.md`](V4_ANALYSIS_PLAN.md). Interpretation: [`V4_ROOT_CAUSE_AUDIT.md`](V4_ROOT_CAUSE_AUDIT.md).",
     "All data were seen in v1–v3: diagnostic only.", "",
     "Columns: r_h = direction-adjusted move to candle H in ATR after costs (H: 1H 24, 4H 30, 1D 20, 1W 13).",
     "Excess columns are r_h minus a per-event control on the same symbol and side, mean [95% month-cluster CI]:",
     "**R0** every candle of the symbol in the window; **R1a** the 2H candles after the event (post hoc, see audit);",
     "**R2** candles of the same year in the same HTF state; **R3** same year and volatility tercile.",
     "R1 (±2H, pre-declared) is in the json; it is biased against breaks by construction (audit finding F5).",
     "top5 = share of the cell's gross gains from its best 5% of events. adq = ≥100 events in ≥24 months.", ""]

for tf in TFS:
    r = R[tf]
    L += [f"## {tf} ({r['symbols']} symbols)", ""]
    for grp in GROUPS:
        L += [f"### {tf} · {grp}", "",
              "| side | set | n | months | mean r_h [95% CI] | median | mean w/o top 1% | top5 | 2ATR-first / 1ATR-first | MFE / MAE med | xR0 | xR1a | xR2 | xR3 | MDE | adq |",
              "|---|---|---:|---:|---|---:|---:|---:|---:|---:|---|---|---|---|---:|---|"]
        for k, c in r["cells"].items():
            g, side, name = k.split("|")
            if g != grp:
                continue
            L.append(f"| {side} | {name} | {c['n']} | {c['months']} | {f(c['mean'])} [{f(c['lo'])}, {f(c['hi'])}] | "
                     f"{f(c['median'])} | {f(c['mean_ex_top1'])} | {f(c['top5_share_of_gains'], sign=False)} | "
                     f"{100 * c['hit_2v1']:.0f}% / {100 * c['stop_1']:.0f}% | {f(c['mfe_med'], sign=False)} / {f(c['mae_med'], sign=False)} | "
                     f"{ci(c['xR0'])} | {ci(c['xR1a'])} | {ci(c['xR2'])} | {f(c['xR3'][0])} | {f(c['mde'], sign=False)} | "
                     f"{'yes' if c['adequate'] else 'no'} |")
        L.append("")
    L += [f"### {tf} · horizons, lateness and 'looks right' (all groups pooled)", "",
          "| side | set | xR1a short H/4 | xR1a H | xR1a long 2H | move before signal, ATR (med) | bars since extreme (med) | MFE ≥ 2 ATR | same, local random | MFE ≥ 2 ATR but r_h ≤ 0 |",
          "|---|---|---|---|---|---:|---:|---:|---:|---:|"]
    for k, c in r["cells"].items():
        g, side, name = k.split("|")
        if g != "all":
            continue
        L.append(f"| {side} | {name} | {ci(c['xR1_s'])}* | {ci(c['xR1a'])} | {ci(c['xR1_l'])}* | {f(c.get('late_atr_med'), sign=False)} | "
                 f"{f(c.get('late_bars_med'), 0, False)} | {100 * c['mfe2']:.0f}% | {100 * c['mfe2_local_random']:.0f}% | {100 * c['mfe2_but_lost']:.0f}% |")
    L += ["", "\\* short/long horizons use the ±2H local control R1 (pre-declared), which is biased against breaks.", ""]
    L += [f"### {tf} · detection of ex-post swings (zigzag ≥ 4 ATR; future data used for scoring only)", "",
          "| group | side | set | legs | detected | lag, bars (med) | share of leg left at signal (med) |", "|---|---|---|---:|---:|---:|---:|"]
    for k, d in r["detection"].items():
        g, side, name = k.split("|")
        L.append(f"| {g} | {side} | {name} | {d['legs']} | {100 * d['detected']:.0f}% | {f(d['lag_med'], 0, False)} | {f(d['captured_med'], sign=False)} |")
    L += ["", f"### {tf} · HTF state (share of candles where a with-HTF signal of each side is possible; run lengths in chart candles)", "",
          "| group | with-HTF bullish possible | with-HTF bearish possible | HTF1 state run (med) | HTF2 state run (med / mean) |", "|---|---:|---:|---:|---:|"]
    for g, h in r["htf"].items():
        L.append(f"| {g} | {100 * h['with_bull']:.0f}% | {100 * h['with_bear']:.0f}% | {f(h['t1_run_med'], 0, False)} | "
                 f"{f(h['t2_run_med'], 0, False)} / {f(h['t2_run_mean'], 0, False)} |")
    L += ["", f"### {tf} · regime at entry (excess vs R1, pre-declared control, all groups)", "",
          "| key | n | mean r_h | xR1 [95% CI] |", "|---|---:|---:|---|"]
    for k, d in r["regimes"].items():
        L.append(f"| {k} | {d['n']} | {f(d['mean_r'])} | {ci(d['xR1'])} |")
    L += ["", f"Strategy-twin path check: {r['twin']['affected']} of {r['twin']['trades']} simulated MAJOR trades receive a "
          "same-direction MAJOR signal while open (Pine twin resets stop and time-exit clock there; evaluate.simulate does not).", ""]

(ROOT / "reports" / "V4_TABLES.md").write_text("\n".join(L) + "\n")
print("wrote reports/V4_TABLES.md")
