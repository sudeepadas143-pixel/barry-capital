def generate(S: dict) -> str:
    bad = unsupported(S)
    if bad:
        raise ValueError(f"shipped spec uses features Pine cannot compute: {bad}")
    htf = ""
    if uses_htf(S):
        htf = ("htfStr = bucket == 3 ? \"M\" : bucket == 2 ? \"W\" : bucket == 1 ? \"D\" : \"240\"\n"
               "LH = bucket == 3 ? 12 : bucket == 2 ? 26 : bucket == 1 ? 63 : 126\n"
               "fHtfRng = request.security(syminfo.tickerid, htfStr, rngOf(LH)[1], lookahead = barmerge.lookahead_on)")
    return TEMPLATE.replace("__HTF__", htf).replace("__SCORES__", score_block(S, "top") + "\n\n" + score_block(S, "bot"))


if __name__ == "__main__":
    S = json.loads(SPEC.read_text())
    OUT.write_text(generate(S))
    print("wrote", OUT)
