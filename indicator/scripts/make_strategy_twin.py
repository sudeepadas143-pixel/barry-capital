"""Generate pine/HighConvictionMTF_strategy.pine from the indicator, so the two never drift.

The twin is the indicator with three mechanical changes:
1. `indicator(...)` becomes `strategy(...)` with next-open fills, no pyramiding, 0.10% commission
   per side (crypto default; change it in Properties for other markets), 2 ticks slippage.
2. `alertcondition()` lines are removed (TradingView allows them only in indicators).
3. A trade block is appended that trades exactly the markers the indicator draws (bullSig /
   bearSig) with the research exit rules: initial stop 2 ATR, trailing stop 3 ATR from the best
   close, reversal on an opposite signal, time exit after the profile's max hold.
   Two documented differences from the Python simulator: the initial stop is set from the
   signal candle's close (Pine does not know the fill price yet) until the first candle after
   the fill, and a time exit fills at the next open.

    python scripts/make_strategy_twin.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "pine" / "HighConvictionMTF.pine"
DST = ROOT / "pine" / "HighConvictionMTF_strategy.pine"

DECL = ('strategy("High-Conviction MTF Trend Signals — Strategy Tester twin", shorttitle = "HC-MTF ST", '
        'overlay = true, max_labels_count = 500, pyramiding = 0, process_orders_on_close = false, '
        'calc_on_every_tick = false, initial_capital = 100000, default_qty_type = strategy.percent_of_equity, '
        'default_qty_value = 100, commission_type = strategy.commission.percent, commission_value = 0.1, slippage = 2)')

TRADES = '''
// ── Strategy Tester twin: trade exactly the drawn markers ────────────────────
// Generated by scripts/make_strategy_twin.py from the indicator; edit the indicator, not this.
GT = "Strategy Tester"
maxHold = input.int(0, "Time exit after N candles (0 = profile: 1H 72, 4H 60, 1D/1W 60/26)", minval = 0, group = GT)
holdN = maxHold > 0 ? maxHold : profile == "1H" ? 72 : profile == "4H" ? 60 : profile == "1D" ? 60 : 26
var float best = na
var float stopPx = na
var int entryBar = na
var float sigAtr = na
if bullSig
    strategy.entry("BULLISH", strategy.long)
    stopPx := close - 2.0 * atr
    sigAtr := atr
    best := close
    entryBar := bar_index + 1
if bearSig
    strategy.entry("BEARISH", strategy.short)
    stopPx := close + 2.0 * atr
    sigAtr := atr
    best := close
    entryBar := bar_index + 1
pos = strategy.position_size
if pos != 0 and bar_index == entryBar
    stopPx := strategy.position_avg_price - math.sign(pos) * 2.0 * sigAtr     // re-anchor on the actual fill
if pos != 0 and bar_index >= entryBar
    best := pos > 0 ? math.max(best, close) : math.min(best, close)
    trail = best - math.sign(pos) * 3.0 * atr
    stopPx := pos > 0 ? math.max(stopPx, trail) : math.min(stopPx, trail)
    if bar_index - entryBar + 1 >= holdN
        strategy.close_all(comment = "time")
if pos > 0
    strategy.exit("stop L", "BULLISH", stop = stopPx)
if pos < 0
    strategy.exit("stop S", "BEARISH", stop = stopPx)
'''


def make() -> str:
    src = SRC.read_text()
    out = re.sub(r"^indicator\(.*\)$", DECL, src, count=1, flags=re.M)
    out = "\n".join(l for l in out.split("\n") if not l.startswith("alertcondition("))
    return out.rstrip() + "\n" + TRADES


if __name__ == "__main__":
    DST.write_text(make())
    print("wrote", DST)
