"""Write the screened components, thresholds and out-of-sample evidence lines into the Pine file.

Reads reports/active_config.json, reports/results.json and reports/verdicts.json (from
scripts/apply_screening.py and `python -m hcmtf.report2`) and replaces the block between
`// <<VALIDATED` and `// VALIDATED>>`.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PINE = ROOT / "pine" / "HighConvictionMTF.pine"
FLAGS = [("USE_MOMENTUM", "momentum"), ("USE_STRENGTH", "strength"), ("USE_DISPLACEMENT", "displacement"),
         ("USE_FVG", "fvg"), ("USE_VOLUME", "volume"), ("USE_SWEEP", "sweep"), ("USE_LTF", "ltf_momentum")]
FILTS = [("FLT_RANGE", "not_range"), ("FLT_SHOCK", "not_shock"), ("FLT_SPIKE", "not_spike_wick"),
         ("FLT_WEEKEND", "not_weekend")]


def line(tf, r, v, grp):
    verdict = v.get(f"{tf} {grp}", ["UNPROVEN"])[0]
    o = (r.get(f"fresh_{grp}") or {}).get("events", {}).get("MAJOR (realignment)", {})
    if not o.get("n"):
        return f"MAJOR {verdict}: no MAJOR signals on unseen symbols"
    return (f"MAJOR {verdict} on unseen {'crypto' if grp == 'crypto' else 'non-crypto'} symbols: n={o['n']}, "
            f"{o['mean_r']:+.2f} ATR vs {o['rand_mean_r']:+.2f} random (95% CI {o['mean_r_lo']:+.2f}..{o['mean_r_hi']:+.2f})")


def main():
    cfg = json.loads((ROOT / "reports" / "active_config.json").read_text())
    res = json.loads((ROOT / "reports" / "results.json").read_text())
    ver = json.loads((ROOT / "reports" / "verdicts.json").read_text())
    rows = ["// <<VALIDATED (generated by scripts/sync_pine.py — do not edit by hand)"]
    import sys
    sys.path.insert(0, str(ROOT))
    from hcmtf.report2 import active_params
    for tf in ("1H", "4H", "1D", "1W"):
        p = active_params(tf)
        rows += [f"VAL_CONFIRM_{tf} = {float(p.confirm)}", f"VAL_MAJOR_{tf}   = {float(p.major)}"]
    rows += [f"{k} = {'true' if c in cfg['evidence'] else 'false'}" for k, c in FLAGS]
    rows += [f"{k} = {'true' if c in cfg['filters'] else 'false'}" for k, c in FILTS]
    rows.append('CRYPTO_ONLY = "|' + "|".join(cfg["crypto_only"]) + '|"')
    for tf in ("1H", "4H", "1D", "1W"):
        rows.append(f'VAL_TEXT_{tf}_C = "{line(tf, res[tf], ver, "crypto")}"')
        rows.append(f'VAL_TEXT_{tf}_O = "{line(tf, res[tf], ver, "other")}"')
    rows.append("// VALIDATED>>")
    perp = [c for c in ("perp_ok", "basis_ok", "oi_up") if c in cfg["evidence"]]
    if perp:
        raise SystemExit(f"perp features {perp} survived screening: add their Pine inputs before syncing")
    PINE.write_text(re.sub(r"// <<VALIDATED.*?// VALIDATED>>", "\n".join(rows), PINE.read_text(), flags=re.S))
    print("\n".join(rows))


if __name__ == "__main__":
    main()
