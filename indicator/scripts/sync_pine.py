"""Write the validated thresholds and evidence lines into the Pine script.

Reads reports/results.json and reports/verdicts.json (made by `python -m hcmtf.report`)
and replaces the block between `// <<VALIDATED` and `// VALIDATED>>`. The thresholds are
the ones chosen on data BEFORE the holdout, so the holdout numbers stay honest.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PINE = ROOT / "pine" / "HighConvictionMTF.pine"


def line(tf: str, r: dict, v: dict) -> str:
    o = r["oos"].get("major", {})
    verdict = v.get(f"{tf} major", ["UNPROVEN"])[0]
    if not o or not o.get("n"):
        return f"MAJOR {verdict}: no out-of-sample major signals"
    h = r["hold"].get("major", {})
    hold = (f"; holdout {h['mean_r']:+.2f} vs {h['rand_mean_r']:+.2f}" if h.get("n") else "; no holdout signals")
    return (f"MAJOR {verdict} · OOS n={o['n']}, hit {100 * o['precision']:.0f}% vs {100 * o['rand_precision']:.0f}% random, "
            f"{o['mean_r']:+.2f} ATR vs {o['rand_mean_r']:+.2f} random{hold}")


def main() -> None:
    res = json.loads((ROOT / "reports" / "results.json").read_text())
    ver = json.loads((ROOT / "reports" / "verdicts.json").read_text())
    rows = ["// <<VALIDATED (generated by scripts/sync_pine.py from reports/results.json — do not edit by hand)"]
    for tf in ("1H", "4H", "1D", "1W"):
        h = res[tf]["holdout"]
        rows.append(f"VAL_CONFIRM_{tf} = {h['confirm']}")
        rows.append(f"VAL_MAJOR_{tf}   = {h['major']}")
    for tf in ("1H", "4H", "1D", "1W"):
        rows.append(f'VAL_TEXT_{tf} = "{line(tf, res[tf], ver)}"')
    rows.append("// VALIDATED>>")
    src = PINE.read_text()
    new = re.sub(r"// <<VALIDATED.*?// VALIDATED>>", "\n".join(rows), src, flags=re.S)
    PINE.write_text(new)
    print("\n".join(rows))


if __name__ == "__main__":
    main()
