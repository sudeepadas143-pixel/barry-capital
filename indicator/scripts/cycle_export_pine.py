"""Generate pine/HC_CycleEngine.pine from reports/cycle_model_spec.json (CYCLE_CONFIG.md §7).

The research spec (coefficients, means, standard deviations, thresholds per TF bucket, direction
and volume group) is written into the Pine source verbatim, so the indicator computes exactly the
shipped CY-1 model. The production indicator pine/HighConvictionMTF*.pine is not touched.

    python scripts/cycle_export_pine.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "reports" / "cycle_model_spec.json"
OUT = ROOT / "pine" / "HC_CycleEngine.pine"
BUCKET = {"1W": 3, "1D": 2, "4H": 1, "1H": 0}
HTF_STR = {"1W": '"M"', "1D": '"W"', "4H": '"D"', "1H": '"240"'}
PINE_FEAT = {  # research feature name -> Pine series name (identical definitions, see the feature block)
    "ext_c": "fExtC", "ext_f": "fExtF", "rng": "fRng", "slope": "fSlope", "since_hh": "fSinceHH", "since_ll": "fSinceLL",
    "atr_rank": "fAtrRank", "rsi": "fRsi", "rsi_slope": "fRsiSlope", "rsi_gap_hi": "fRsiGapHi", "rsi_gap_lo": "fRsiGapLo",
    "hist": "fHist", "hist_acc": "fHistAcc", "relvol": "fRelVol", "vtrend": "fVTrend", "effort": "fEffort", "vpress": "fVPress",
    "i_rng_gaphi": "fIRngGapHi", "i_rng_gaplo": "fIRngGapLo", "i_ext_relvol": "fIExtRelVol", "htf_rng": "fHtfRng"}


def _num(x: float) -> str:
    return f"{x:.10g}"


def expr(spec: dict) -> str:
    if spec["kind"] == "base":
        return f"{_num(spec['sign'])} * {PINE_FEAT[spec['feature']]}"
    terms = [_num(spec["intercept"])]
    for f, mu, sd, b in zip(spec["features"], spec["mu"], spec["sd"], spec["coef"]):
        if f not in PINE_FEAT:
            raise ValueError(f"feature {f!r} cannot be computed in Pine")
        terms.append(f"{_num(b)} * z({PINE_FEAT[f]}, {_num(mu)}, {_num(sd)})")
    return "sig(" + " + ".join(terms) + ")"


def score_block(S: dict, d: str) -> str:
    lines = [f"score{d.capitalize()}(bool useVol) =>", "    float p = na", "    float th = na", "    bool lg = false"]
    for tf, b in BUCKET.items():
        if tf not in S["tfs"]:
            continue
        mods = S["tfs"][tf]["models"]
        lines.append(f"    if bucket == {b}")
        for g, cond in (("vol", "useVol"), ("novol", "not useVol")):
            sp = mods[f"{d}|{g}"]
            lines += [f"        if {cond}", f"            p := {expr(sp)}", f"            th := {_num(sp['theta'])}",
                      f"            lg := {'true' if sp['kind'] == 'logit' else 'false'}"]
    lines.append("    [p, th, lg]")
    return "\n".join(lines)


def uses_htf(S: dict) -> bool:
    return any("htf_rng" in m.get("features", []) for t in S["tfs"].values() for m in t["models"].values())


def unsupported(S: dict) -> list[str]:
    return sorted({f for t in S["tfs"].values() for m in t["models"].values() for f in m.get("features", []) if f not in PINE_FEAT})


